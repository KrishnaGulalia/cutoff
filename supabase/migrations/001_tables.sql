-- Supabase Auth owns credentials; cutoff.users stores the student profile.
CREATE SCHEMA cutoff;
SET LOCAL search_path = cutoff, pg_catalog;

-- 1. Accounts and papers -------------------------------------------------------

CREATE TABLE users (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
    user_name TEXT NOT NULL CHECK (length(trim(user_name)) BETWEEN 1 AND 80),
    user_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tests (
    test_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_title        TEXT NOT NULL CHECK (btrim(test_title) <> ''),
    exam_year         SMALLINT NOT NULL CHECK (exam_year BETWEEN 2000 AND 9999),
    session_label     TEXT NOT NULL CHECK (btrim(session_label) <> ''),
    duration_minutes  INTEGER NOT NULL CHECK (duration_minutes > 0),
    test_created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Classification -----------------------------------------------------------

CREATE TABLE subjects (
    subject_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name  TEXT NOT NULL UNIQUE CHECK (btrim(subject_name) <> '')
);

CREATE TABLE chapters (
    chapter_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id    BIGINT NOT NULL REFERENCES subjects(subject_id) ON DELETE RESTRICT,
    chapter_name  TEXT NOT NULL CHECK (btrim(chapter_name) <> ''),
    CONSTRAINT chapters_name_per_subject UNIQUE (subject_id, chapter_name)
);

CREATE TABLE topics (
    topic_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id  BIGINT NOT NULL REFERENCES chapters(chapter_id) ON DELETE RESTRICT,
    topic_name  TEXT NOT NULL CHECK (btrim(topic_name) <> ''),
    CONSTRAINT topics_name_per_chapter UNIQUE (chapter_id, topic_name)
);

-- 3. Question content, options and answer keys ---------------------------------

CREATE TABLE questions (
    question_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_id           BIGINT NOT NULL REFERENCES chapters(chapter_id) ON DELETE RESTRICT,
    question_text        TEXT NOT NULL CHECK (btrim(question_text) <> ''),
    question_type        TEXT NOT NULL CHECK (
        question_type IN ('SINGLE_CHOICE', 'MULTIPLE_SELECT', 'NUMERICAL')
    ),
    difficulty           TEXT NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
    explanation_text     TEXT,
    question_created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE question_topics (
    question_id  BIGINT PRIMARY KEY REFERENCES questions(question_id) ON DELETE RESTRICT,
    topic_id     BIGINT NOT NULL REFERENCES topics(topic_id) ON DELETE RESTRICT
);

CREATE TABLE question_options (
    question_id  BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    option_label TEXT NOT NULL CHECK (option_label ~ '^[A-Z]$'),
    option_text  TEXT NOT NULL,
    PRIMARY KEY (question_id, option_label)
);

CREATE TABLE correct_options (
    question_id  BIGINT NOT NULL,
    option_label TEXT NOT NULL,
    PRIMARY KEY (question_id, option_label),
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

CREATE TABLE numerical_keys (
    question_id   BIGINT PRIMARY KEY REFERENCES questions(question_id) ON DELETE RESTRICT,
    accepted_min  NUMERIC NOT NULL,
    accepted_max  NUMERIC NOT NULL,
    CONSTRAINT numerical_keys_valid_interval CHECK (
        accepted_min <= accepted_max
        AND accepted_min NOT IN ('NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC)
        AND accepted_max NOT IN ('NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC)
    )
);

CREATE TABLE question_images (
    question_id     BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    image_position  INTEGER NOT NULL CHECK (image_position > 0),
    image_url       TEXT NOT NULL CHECK (btrim(image_url) <> ''),
    PRIMARY KEY (question_id, image_position)
);

CREATE TABLE option_images (
    question_id     BIGINT NOT NULL,
    option_label    TEXT NOT NULL,
    image_position  INTEGER NOT NULL CHECK (image_position > 0),
    image_url       TEXT NOT NULL CHECK (btrim(image_url) <> ''),
    PRIMARY KEY (question_id, option_label, image_position),
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

-- 4. Paper composition --------------------------------------------------------

CREATE TABLE test_questions (
    test_id            BIGINT NOT NULL REFERENCES tests(test_id) ON DELETE RESTRICT,
    question_id        BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    position           INTEGER NOT NULL CHECK (position > 0),
    marks_correct      NUMERIC NOT NULL DEFAULT 4,
    marks_incorrect    NUMERIC NOT NULL DEFAULT -1,
    marks_unattempted  NUMERIC NOT NULL DEFAULT 0,
    PRIMARY KEY (test_id, question_id),
    CONSTRAINT test_questions_position_unique UNIQUE (test_id, position),
    CONSTRAINT test_questions_signed_marks CHECK (
        marks_correct > 0 AND marks_correct < 'Infinity'::NUMERIC
        AND marks_incorrect <= 0 AND marks_incorrect > '-Infinity'::NUMERIC
        AND marks_unattempted = 0
    )
);

-- 5. Attempts and student responses -------------------------------------------

CREATE TABLE attempts (
    attempt_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    test_id         BIGINT NOT NULL REFERENCES tests(test_id) ON DELETE RESTRICT,
    started_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at    TIMESTAMPTZ,
    attempt_status  TEXT NOT NULL DEFAULT 'IN_PROGRESS',
    CONSTRAINT attempts_valid_state CHECK (
        (attempt_status = 'IN_PROGRESS' AND submitted_at IS NULL)
        OR (attempt_status = 'SUBMITTED' AND submitted_at IS NOT NULL
            AND submitted_at >= started_at)
    )
);

-- Repeated submitted attempts are allowed; concurrent active attempts are not.
CREATE UNIQUE INDEX attempts_one_active_per_user_test
    ON attempts(user_id, test_id) WHERE attempt_status = 'IN_PROGRESS';

CREATE TABLE answers (
    attempt_id          BIGINT NOT NULL REFERENCES attempts(attempt_id) ON DELETE RESTRICT,
    question_id         BIGINT NOT NULL REFERENCES questions(question_id) ON DELETE RESTRICT,
    numerical_response  NUMERIC,
    marked_for_review   BOOLEAN NOT NULL DEFAULT false,
    time_spent_seconds  INTEGER NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
    answer_updated_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (attempt_id, question_id),
    CONSTRAINT answers_finite_number CHECK (
        numerical_response IS NULL OR numerical_response NOT IN (
            'NaN'::NUMERIC, 'Infinity'::NUMERIC, '-Infinity'::NUMERIC
        )
    )
);

CREATE TABLE answer_options (
    attempt_id   BIGINT NOT NULL,
    question_id  BIGINT NOT NULL,
    option_label TEXT NOT NULL,
    PRIMARY KEY (attempt_id, question_id, option_label),
    FOREIGN KEY (attempt_id, question_id)
        REFERENCES answers(attempt_id, question_id) ON DELETE RESTRICT,
    FOREIGN KEY (question_id, option_label)
        REFERENCES question_options(question_id, option_label) ON DELETE RESTRICT
);

